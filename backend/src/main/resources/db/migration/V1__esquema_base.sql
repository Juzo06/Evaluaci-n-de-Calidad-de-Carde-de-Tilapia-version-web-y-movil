-- =====================================================================
-- V1 - Esquema base (réplica del esquema creado a mano en Supabase)
--
-- Todas las sentencias usan IF NOT EXISTS: en Supabase, donde las tablas
-- ya existen, no hace nada; en una base vacía (Testcontainers, otro
-- compañero, CI) crea el esquema completo. No incluye las políticas RLS
-- propias de Supabase para que sea portable a cualquier PostgreSQL.
-- =====================================================================

CREATE TABLE IF NOT EXISTS estacion (
    id      INT4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre  VARCHAR(100) NOT NULL,
    CONSTRAINT estacion_nombre_key UNIQUE (nombre),
    CONSTRAINT estacion_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS estado_lote (
    id      INT2 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo  VARCHAR(20) NOT NULL,
    CONSTRAINT estado_lote_codigo_key UNIQUE (codigo),
    CONSTRAINT estado_lote_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS parte_pez (
    id      INT2 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo  VARCHAR(10) NOT NULL,
    CONSTRAINT parte_pez_codigo_key UNIQUE (codigo),
    CONSTRAINT parte_pez_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS rol (
    id      INT2 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo  VARCHAR(20) NOT NULL,
    CONSTRAINT rol_codigo_key UNIQUE (codigo),
    CONSTRAINT rol_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS tipo_evento (
    id           INT2 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo       VARCHAR(40) NOT NULL,
    descripcion  VARCHAR(150) NULL,
    CONSTRAINT tipo_evento_codigo_key UNIQUE (codigo),
    CONSTRAINT tipo_evento_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS usuario (
    id               INT4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombres          VARCHAR(100) NOT NULL,
    apellidos        VARCHAR(100) NOT NULL,
    correo           VARCHAR(150) NOT NULL,
    telefono         VARCHAR(20) NULL,
    nombre_usuario   VARCHAR(30) NOT NULL,
    contrasena_hash  VARCHAR(255) NOT NULL,
    rol_id           INT2 NOT NULL,
    activo           BOOL DEFAULT TRUE NOT NULL,
    CONSTRAINT usuario_correo_key UNIQUE (correo),
    CONSTRAINT usuario_nombre_usuario_key UNIQUE (nombre_usuario),
    CONSTRAINT usuario_pkey PRIMARY KEY (id),
    CONSTRAINT usuario_rol_id_fkey FOREIGN KEY (rol_id) REFERENCES rol (id) DEFERRABLE
);

CREATE TABLE IF NOT EXISTS lote (
    id                       INT4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id               INT4 NOT NULL,
    estacion_id              INT4 NOT NULL,
    estado_lote_id           INT2 NOT NULL,
    codigo                   VARCHAR(30) NOT NULL,
    fecha_captura            DATE NOT NULL,
    peso                     NUMERIC(10, 2) NOT NULL,
    numero_unidades_muestra  INT4 NOT NULL,
    observaciones            VARCHAR(500) NULL,
    clasificacion_final      NUMERIC(4, 2) NULL,
    CONSTRAINT ck_lote_clasificacion CHECK (clasificacion_final IS NULL OR (clasificacion_final >= 1 AND clasificacion_final <= 5)),
    CONSTRAINT ck_lote_codigo CHECK (codigo ~ '^SECCT-[0-9]{8}-[0-9]{3}$'),
    CONSTRAINT ck_lote_peso CHECK (peso >= 0.01),
    CONSTRAINT ck_lote_unidades CHECK (numero_unidades_muestra >= 1),
    CONSTRAINT lote_codigo_key UNIQUE (codigo),
    CONSTRAINT lote_pkey PRIMARY KEY (id),
    CONSTRAINT lote_estacion_id_fkey FOREIGN KEY (estacion_id) REFERENCES estacion (id) DEFERRABLE,
    CONSTRAINT lote_estado_lote_id_fkey FOREIGN KEY (estado_lote_id) REFERENCES estado_lote (id) DEFERRABLE,
    CONSTRAINT lote_usuario_id_fkey FOREIGN KEY (usuario_id) REFERENCES usuario (id) DEFERRABLE
);

CREATE TABLE IF NOT EXISTS evaluacion (
    id                INT4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    lote_id           INT4 NOT NULL,
    id_imagen         VARCHAR(255) NOT NULL,
    clasificacion     INT4 NOT NULL,
    fecha_evaluacion  TIMESTAMP DEFAULT now() NOT NULL,
    CONSTRAINT ck_evaluacion_clasificacion CHECK (clasificacion >= 1 AND clasificacion <= 5),
    CONSTRAINT evaluacion_pkey PRIMARY KEY (id),
    CONSTRAINT evaluacion_lote_id_fkey FOREIGN KEY (lote_id) REFERENCES lote (id) ON DELETE RESTRICT DEFERRABLE
);

CREATE TABLE IF NOT EXISTS log (
    id              INT8 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tipo_evento_id  INT2 NOT NULL,
    usuario_id      INT4 NULL,
    lote_id         INT4 NULL,
    evaluacion_id   INT4 NULL,
    fecha_hora      TIMESTAMP DEFAULT now() NOT NULL,
    descripcion     VARCHAR(500) NULL,
    CONSTRAINT log_pkey PRIMARY KEY (id),
    CONSTRAINT log_evaluacion_id_fkey FOREIGN KEY (evaluacion_id) REFERENCES evaluacion (id) ON DELETE SET NULL DEFERRABLE,
    CONSTRAINT log_lote_id_fkey FOREIGN KEY (lote_id) REFERENCES lote (id) ON DELETE SET NULL DEFERRABLE,
    CONSTRAINT log_tipo_evento_id_fkey FOREIGN KEY (tipo_evento_id) REFERENCES tipo_evento (id) DEFERRABLE,
    CONSTRAINT log_usuario_id_fkey FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE SET NULL DEFERRABLE
);

CREATE TABLE IF NOT EXISTS punto_evaluacion (
    id             INT4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    evaluacion_id  INT4 NOT NULL,
    parte_pez_id   INT2 NOT NULL,
    categoria_ntc  INT4 NOT NULL,
    confianza      NUMERIC(5, 4) NOT NULL,
    CONSTRAINT ck_punto_categoria CHECK (categoria_ntc >= 1 AND categoria_ntc <= 5),
    CONSTRAINT ck_punto_confianza CHECK (confianza >= 0 AND confianza <= 1),
    CONSTRAINT punto_evaluacion_pkey PRIMARY KEY (id),
    CONSTRAINT punto_evaluacion_evaluacion_id_fkey FOREIGN KEY (evaluacion_id) REFERENCES evaluacion (id) ON DELETE CASCADE DEFERRABLE,
    CONSTRAINT punto_evaluacion_parte_pez_id_fkey FOREIGN KEY (parte_pez_id) REFERENCES parte_pez (id) DEFERRABLE
);
